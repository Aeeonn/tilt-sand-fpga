#!/usr/bin/env python3
"""Golden model for rtl/platform/pll_sys.sv. See docs/SPEC_pll_sys.md.

Independently derives the expected output-clock periods and the c1-vs-c0
relative phase from the target frequency/phase table in
docs/CONVENTIONS.md "Clock domains (M0)" (using exact Fraction arithmetic,
not by reading the RTL's altpll parameters), and writes
sim/golden/pll_sys_consts.svh for sim/tb/tb_pll_sys.sv to check the
simulated altpll instance against.
"""

import pathlib
from fractions import Fraction

INCLK0_FREQ_HZ = 50_000_000
PS_PER_SEC = Fraction(10**12)

# Target table: name -> (multiply, divide, phase_shift_ps)
OUTPUTS = {
    "c0": (2, 1, 0),      # clk_100,       0 deg
    "c1": (2, 1, -3000),  # clk_100_shift, -3 ns
    "c2": (1, 2, 0),      # clk_25,        0 deg
}


def period_ps(multiply: int, divide: int) -> Fraction:
    freq_hz = Fraction(INCLK0_FREQ_HZ) * multiply / divide
    return PS_PER_SEC / freq_hz


def main() -> None:
    periods = {name: period_ps(m, d) for name, (m, d, _) in OUTPUTS.items()}

    assert periods["c0"] == 10_000, periods["c0"]
    assert periods["c1"] == 10_000, periods["c1"]
    assert periods["c2"] == 40_000, periods["c2"]

    c0_phase_ps = OUTPUTS["c0"][2]
    c1_phase_ps = OUTPUTS["c1"][2]
    c1_rel_phase_ps = (c1_phase_ps - c0_phase_ps) % periods["c0"]
    assert c1_rel_phase_ps == 7_000, c1_rel_phase_ps

    refclk_period_ps = PS_PER_SEC / INCLK0_FREQ_HZ
    assert refclk_period_ps == 20_000, refclk_period_ps

    out_path = pathlib.Path(__file__).parent / "pll_sys_consts.svh"
    out_path.write_text(
        "// Generated by sim/golden/pll_sys.py - do not edit by hand.\n"
        f"`define PLL_REFCLK_PERIOD_PS {int(refclk_period_ps)}\n"
        f"`define PLL_C0_PERIOD_PS {int(periods['c0'])}\n"
        f"`define PLL_C1_PERIOD_PS {int(periods['c1'])}\n"
        f"`define PLL_C2_PERIOD_PS {int(periods['c2'])}\n"
        f"`define PLL_C1_REL_PHASE_PS {int(c1_rel_phase_ps)}\n"
    )
    print(f"wrote {out_path}")
    for name, p in periods.items():
        print(f"{name}: period={int(p)} ps")
    print(f"c1 relative phase = {int(c1_rel_phase_ps)} ps")


if __name__ == "__main__":
    main()
