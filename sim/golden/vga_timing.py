#!/usr/bin/env python3
"""Golden model for rtl/platform/vga_timing.sv. See docs/SPEC_vga_timing.md.

Walks every (h_count, v_count) pair for one frame, checks the derived
constants in the spec, and emits sim/golden/vga_timing_consts.svh for
sim/tb/tb_vga_timing.sv to `include.
"""

import pathlib

H_VISIBLE, H_FRONT, H_SYNC, H_BACK = 640, 16, 96, 48
V_VISIBLE, V_FRONT, V_SYNC, V_BACK = 480, 10, 2, 33

H_TOTAL = H_VISIBLE + H_FRONT + H_SYNC + H_BACK
V_TOTAL = V_VISIBLE + V_FRONT + V_SYNC + V_BACK
FRAME_CYCLES = H_TOTAL * V_TOTAL


def signals(h_count: int, v_count: int):
    hsync = not (H_VISIBLE + H_FRONT <= h_count < H_VISIBLE + H_FRONT + H_SYNC)
    vsync = not (V_VISIBLE + V_FRONT <= v_count < V_VISIBLE + V_FRONT + V_SYNC)
    video_on = h_count < H_VISIBLE and v_count < V_VISIBLE
    return hsync, vsync, video_on, h_count, v_count


def main() -> None:
    video_on_cycles = 0
    hsync_active_cycles = 0
    vsync_active_cycles = 0
    first_on = None
    last_on = None

    for v_count in range(V_TOTAL):
        for h_count in range(H_TOTAL):
            hsync, vsync, video_on, px, py = signals(h_count, v_count)
            if not hsync:
                hsync_active_cycles += 1
            if not vsync:
                vsync_active_cycles += 1
            if video_on:
                video_on_cycles += 1
                if first_on is None:
                    first_on = (px, py)
                last_on = (px, py)

    assert H_TOTAL == 800, H_TOTAL
    assert V_TOTAL == 525, V_TOTAL
    assert FRAME_CYCLES == 420_000, FRAME_CYCLES
    assert video_on_cycles == H_VISIBLE * V_VISIBLE == 307_200, video_on_cycles
    assert hsync_active_cycles == V_TOTAL * H_SYNC == 50_400, hsync_active_cycles
    assert vsync_active_cycles == V_SYNC * H_TOTAL == 1_600, vsync_active_cycles
    assert first_on == (0, 0), first_on
    assert last_on == (H_VISIBLE - 1, V_VISIBLE - 1), last_on

    out_path = pathlib.Path(__file__).parent / "vga_timing_consts.svh"
    out_path.write_text(
        "// Generated by sim/golden/vga_timing.py - do not edit by hand.\n"
        f"`define VGA_H_VISIBLE {H_VISIBLE}\n"
        f"`define VGA_H_FRONT {H_FRONT}\n"
        f"`define VGA_H_SYNC {H_SYNC}\n"
        f"`define VGA_H_BACK {H_BACK}\n"
        f"`define VGA_H_TOTAL {H_TOTAL}\n"
        f"`define VGA_V_VISIBLE {V_VISIBLE}\n"
        f"`define VGA_V_FRONT {V_FRONT}\n"
        f"`define VGA_V_SYNC {V_SYNC}\n"
        f"`define VGA_V_BACK {V_BACK}\n"
        f"`define VGA_V_TOTAL {V_TOTAL}\n"
        f"`define VGA_FRAME_CYCLES {FRAME_CYCLES}\n"
        f"`define VGA_VIDEO_ON_CYCLES {video_on_cycles}\n"
        f"`define VGA_HSYNC_ACTIVE_CYCLES {hsync_active_cycles}\n"
        f"`define VGA_VSYNC_ACTIVE_CYCLES {vsync_active_cycles}\n"
    )
    print(f"wrote {out_path}")
    print(f"FRAME_CYCLES={FRAME_CYCLES} video_on={video_on_cycles} "
          f"hsync_active={hsync_active_cycles} vsync_active={vsync_active_cycles}")


if __name__ == "__main__":
    main()
