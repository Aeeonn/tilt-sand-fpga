`timescale 1ns/1ps

`include "vga_timing_consts.svh"

module tb_vga_timing;

	localparam time CLK_PERIOD = 2ns; // fast sim clock; checks are cycle-counted, not time-based

	logic clk = 0;
	logic rst_n;
	logic hsync, vsync, video_on;
	logic [9:0] pixel_x, pixel_y;

	int pass_count = 0;
	int fail_count = 0;
	int printed_fails = 0;
	localparam int MAX_PRINTED_FAILS = 10;

	int ref_h, ref_v;
	logic ref_hsync, ref_vsync, ref_video_on;

	longint video_on_count, hsync_active_count, vsync_active_count;

	vga_timing dut (
		.clk      (clk),
		.rst_n    (rst_n),
		.hsync    (hsync),
		.vsync    (vsync),
		.video_on (video_on),
		.pixel_x  (pixel_x),
		.pixel_y  (pixel_y)
	);

	always #(CLK_PERIOD/2) clk = ~clk;

	task automatic step();
		@(posedge clk);
		#1;
	endtask

	task automatic check(string name, logic got, logic exp);
		if (got === exp) begin
			pass_count++;
		end else begin
			fail_count++;
			if (printed_fails < MAX_PRINTED_FAILS) begin
				$display("FAIL: %s - expected %b got %b at time %0t", name, exp, got, $time);
				printed_fails++;
			end
		end
	endtask

	task automatic check10(string name, logic [9:0] got, logic [9:0] exp);
		if (got === exp) begin
			pass_count++;
		end else begin
			fail_count++;
			if (printed_fails < MAX_PRINTED_FAILS) begin
				$display("FAIL: %s - expected %0d got %0d at time %0t", name, exp, got, $time);
				printed_fails++;
			end
		end
	endtask

	task automatic check_count(string name, longint got, longint exp);
		if (got == exp) begin
			pass_count++;
		end else begin
			fail_count++;
			$display("FAIL: %s - expected %0d got %0d", name, exp, got);
		end
	endtask

	// Independent reference model: same formulas as docs/SPEC_vga_timing.md,
	// driven from constants generated by sim/golden/vga_timing.py.
	function automatic void ref_signals(
			input  int   h,
			input  int   v,
			output logic r_hsync,
			output logic r_vsync,
			output logic r_video_on
	);
		r_hsync    = ~(h >= `VGA_H_VISIBLE+`VGA_H_FRONT && h < `VGA_H_VISIBLE+`VGA_H_FRONT+`VGA_H_SYNC);
		r_vsync    = ~(v >= `VGA_V_VISIBLE+`VGA_V_FRONT && v < `VGA_V_VISIBLE+`VGA_V_FRONT+`VGA_V_SYNC);
		r_video_on = (h < `VGA_H_VISIBLE) && (v < `VGA_V_VISIBLE);
	endfunction

	initial begin
		rst_n = 0;
		ref_h = 0;
		ref_v = 0;
		repeat (2) step();
		check("hsync idle during reset", hsync, 1'b1);
		check("vsync idle during reset", vsync, 1'b1);
		check10("pixel_x is 0 during reset", pixel_x, 10'd0);
		check10("pixel_y is 0 during reset", pixel_y, 10'd0);

		@(negedge clk);
		rst_n = 1;

		video_on_count     = 0;
		hsync_active_count = 0;
		vsync_active_count = 0;

		for (int cycle = 0; cycle < `VGA_FRAME_CYCLES + 10; cycle++) begin
			step();

			// Advance the independent reference counters by one cycle.
			if (ref_h == `VGA_H_TOTAL-1) begin
				ref_h = 0;
				ref_v = (ref_v == `VGA_V_TOTAL-1) ? 0 : ref_v + 1;
			end else begin
				ref_h = ref_h + 1;
			end
			ref_signals(ref_h, ref_v, ref_hsync, ref_vsync, ref_video_on);

			check($sformatf("hsync at cycle %0d", cycle), hsync, ref_hsync);
			check($sformatf("vsync at cycle %0d", cycle), vsync, ref_vsync);
			check($sformatf("video_on at cycle %0d", cycle), video_on, ref_video_on);
			check10($sformatf("pixel_x at cycle %0d", cycle), pixel_x, ref_h[9:0]);
			check10($sformatf("pixel_y at cycle %0d", cycle), pixel_y, ref_v[9:0]);

			if (cycle < `VGA_FRAME_CYCLES) begin
				if (video_on) video_on_count++;
				if (!hsync)   hsync_active_count++;
				if (!vsync)   vsync_active_count++;
			end
		end

		check_count("video_on cycles/frame",     video_on_count,     `VGA_VIDEO_ON_CYCLES);
		check_count("hsync active cycles/frame", hsync_active_count, `VGA_HSYNC_ACTIVE_CYCLES);
		check_count("vsync active cycles/frame", vsync_active_count, `VGA_VSYNC_ACTIVE_CYCLES);

		if (fail_count == 0)
			$display("TB tb_vga_timing: %0d/%0d PASS", pass_count, pass_count);
		else
			$display("*** FAIL *** tb_vga_timing: %0d/%0d failed (%0d total)",
								fail_count, fail_count, pass_count + fail_count);

		$finish;
	end

endmodule
